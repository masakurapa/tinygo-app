package main

import (
	"fmt"
	"image"
	_ "image/png"
	"os"

	qrcode "github.com/skip2/go-qrcode"
)

func main() {
	if len(os.Args) < 2 {
		fmt.Fprintln(os.Stderr, "usage: gen <gopher|qr>")
		os.Exit(1)
	}
	switch os.Args[1] {
	case "gopher":
		genGopher()
	case "qr":
		genQR()
	default:
		fmt.Fprintf(os.Stderr, "unknown command: %s\n", os.Args[1])
		os.Exit(1)
	}
}

func genGopher() {
	f, err := os.Open("gopher32.png")
	if err != nil {
		panic(err)
	}
	defer f.Close()

	img, _, err := image.Decode(f)
	if err != nil {
		panic(err)
	}

	b := img.Bounds()
	w, h := b.Max.X, b.Max.Y

	fmt.Println("// Code generated by gen gopher; DO NOT EDIT.")
	fmt.Println("package main")
	fmt.Println()
	fmt.Printf("const gopherW, gopherH int16 = %d, %d\n", w, h)
	fmt.Println()
	fmt.Printf("var gopherBitmap = []uint16{\n")
	for y := 0; y < h; y++ {
		fmt.Printf("\t")
		for x := 0; x < w; x++ {
			r, g, bv, a := img.At(x, y).RGBA()
			var rgb565 uint16
			if a < 0x8000 {
				rgb565 = 0xFFFF
			} else {
				rgb565 = uint16(((r>>8)&0xF8)<<8 | ((g>>8)&0xFC)<<3 | (bv>>8)>>3)
			}
			fmt.Printf("0x%04X,", rgb565)
		}
		fmt.Printf("\n")
	}
	fmt.Println("}")
}

type qrEntry struct {
	name string
	url  string
}

var qrEntries = []qrEntry{
	{"TechnicalPROnX", "https://x.com/kaonavi_devs"},
	{"CorporateWebsite", "https://corp.kaonavi.jp/"},
	{"CasualInterview", "https://recruit.kaonavi.jp/recruit-info"},
	{"MyX", "https://x.com/masakurapa"},
}

func genQR() {
	fmt.Println("// Code generated by gen qr; DO NOT EDIT.")
	fmt.Println("package main")
	fmt.Println()

	for _, e := range qrEntries {
		q, err := qrcode.New(e.url, qrcode.Low)
		if err != nil {
			panic(err)
		}
		bm := q.Bitmap()
		size := len(bm)
		fmt.Printf("var qrBitmap%s = [%d][%d]bool{\n", e.name, size, size)
		for _, row := range bm {
			fmt.Printf("\t{")
			for _, v := range row {
				if v {
					fmt.Printf("true,")
				} else {
					fmt.Printf("false,")
				}
			}
			fmt.Printf("},\n")
		}
		fmt.Printf("}\n\n")

		fmt.Printf("func qr%sBitmap() [][]bool {\n", e.name)
		fmt.Printf("\tout := make([][]bool, %d)\n", size)
		fmt.Printf("\tfor i := range qrBitmap%s {\n", e.name)
		fmt.Printf("\t\tout[i] = qrBitmap%s[i][:]\n", e.name)
		fmt.Printf("\t}\n")
		fmt.Printf("\treturn out\n")
		fmt.Printf("}\n\n")
	}
}
